"""Huckleberry writer. The only module that imports huckleberry_api or touches Firestore.

It does not use `log_sleep` / `log_nursing`, which write under random document ids (so every
re-run duplicates history) and take the timezone offset from *now* (so events on the other side
of a DST change are an hour off). Instead it writes interval documents itself:

- The document id is a pure function of the source row, so `set()` is an idempotent upsert.
- Ids carry a `bdb2hb` marker, so undo lists ids, keeps the marked ones and deletes them.
- `offset` and `end_offset` are computed at each event's own instant.
- Payloads are built with the library's pydantic models, so field names and units follow it.

It never writes `prefs` (lastSleep / lastNursing) or live timers, so undo leaves no trace.
Coupling to library internals is the one call in `_firestore()`; pyproject pins the version.
"""

from __future__ import annotations

import hashlib
import re
import time
from bisect import bisect_left
from collections.abc import AsyncGenerator, Iterable, Mapping, Sequence
from contextlib import asynccontextmanager
from dataclasses import dataclass
from datetime import UTC, datetime
from itertools import batched
from typing import Any, Literal
from zoneinfo import ZoneInfo

import aiohttp
from huckleberry_api import HuckleberryAPI
from huckleberry_api.firebase_types import (
    FirebaseBreastFeedIntervalData,
    FirebaseSleepDetails,
    FirebaseSleepIntervalData,
    to_firebase_dict,
)

from bdb2hb.model import Event, Nursing, Sleep, SourceKey

type Kind = Literal["sleep", "feed"]  # root collection; intervals live at {kind}/{cid}/intervals
type Action = Literal["create", "update", "unchanged", "delete", "skip"]
type Payload = dict[str, Any]
type Snapshot = Mapping[Kind, Mapping[str, Payload]]  # existing interval docs by kind, then id

KINDS: tuple[Kind, ...] = ("sleep", "feed")
_MARKER = "bdb2hb"  # contains "h", so no hex-only id generated by the app can match
# The single definition of "this document was written by bdb2hb". Sleep ids mimic the library's
# 16-hex shape; feed ids mimic "{start_ms}-{20 chars}".
_IMPORTED_ID = re.compile(rf"^(?:{_MARKER}[0-9a-f]{{10}}|\d+-{_MARKER}[0-9a-f]{{14}})$")
_BATCH_LIMIT = 500
_VOLATILE = frozenset({"lastUpdated"})


class ChildNotFound(Exception):
    """--child matched no child, or several. The message lists the names."""


@dataclass(frozen=True, slots=True)
class Op:
    kind: Kind
    doc_id: str
    action: Action
    start: datetime  # UTC, for reporting
    payload: Payload | None  # None unless create or update


@dataclass(frozen=True, slots=True)
class Overlap:
    """An existing interval we did not write that overlaps an imported one: likely a manual duplicate."""

    kind: Kind
    ours_start: datetime
    theirs_start: datetime
    theirs_seconds: float


@dataclass(frozen=True, slots=True)
class Plan:
    """What `apply` would do. Building it only reads. Every op id matches `_IMPORTED_ID`."""

    ops: tuple[Op, ...]
    overlaps: tuple[Overlap, ...] = ()

    def counts(self) -> dict[tuple[Kind, Action], int]:
        out: dict[tuple[Kind, Action], int] = {}
        for op in self.ops:
            out[op.kind, op.action] = out.get((op.kind, op.action), 0) + 1
        return out

    @property
    def pending(self) -> tuple[Op, ...]:
        return tuple(op for op in self.ops if op.action not in ("unchanged", "skip"))


# ---- pure helpers -----------------------------------------------------------------------------


def is_imported(doc_id: str) -> bool:
    return _IMPORTED_ID.fullmatch(doc_id) is not None


def doc_id(kind: Kind, key: SourceKey, start: datetime) -> str:
    """Deterministic id. Identity is the hash of (kind, key); feed ids embed start_ms only to
    look like app ids, and start comes from the same immutable row."""
    h = hashlib.sha256(f"{kind}|{key}".encode()).hexdigest()
    if kind == "sleep":
        return f"{_MARKER}{h[:10]}"
    return f"{int(start.timestamp() * 1000)}-{_MARKER}{h[:14]}"


def offset_minutes(at: datetime, tz: ZoneInfo) -> float:
    """Minutes west of UTC at `at`, the library's sign convention (New York: 300 winter, 240 summer)."""
    off = at.astimezone(tz).utcoffset()
    return -off.total_seconds() / 60 if off is not None else 0.0


def to_doc(event: Event, tz: ZoneInfo, now: float) -> tuple[Kind, str, Payload]:
    start, end = event.span.start, event.span.end
    match event:
        case Sleep():
            start_s, end_s = int(start.timestamp()), int(end.timestamp())
            model = FirebaseSleepIntervalData(
                start=start_s,
                duration=end_s - start_s,
                offset=offset_minutes(start, tz),
                end_offset=offset_minutes(end, tz),
                details=FirebaseSleepDetails(notes=event.notes) if event.notes else None,
                lastUpdated=now,
            )
            return "sleep", doc_id("sleep", event.key, start), to_firebase_dict(model)
        case Nursing():
            model = FirebaseBreastFeedIntervalData(
                mode="breast",
                start=start.timestamp(),
                lastSide=event.last_side,
                lastUpdated=now,
                leftDuration=float(event.left_s),
                rightDuration=float(event.right_s),
                offset=offset_minutes(start, tz),
                end_offset=offset_minutes(end, tz),
                notes=event.notes,
            )
            return "feed", doc_id("feed", event.key, start), to_firebase_dict(model)


def _stable(payload: Payload) -> Payload:
    return {k: v for k, v in payload.items() if k not in _VOLATILE}


def _same(a: Payload, b: Payload) -> bool:
    """Equal ignoring volatile fields and int/float differences from the Firestore round trip."""
    a, b = _stable(a), _stable(b)
    if a.keys() != b.keys():
        return False
    for k in a:
        x, y = a[k], b[k]
        if isinstance(x, dict) and isinstance(y, dict):
            if not _same(x, y):
                return False
        elif isinstance(x, (int, float)) and isinstance(y, (int, float)):
            if abs(x - y) > 1e-6:
                return False
        elif x != y:
            return False
    return True


def _spans(kind: Kind, docs: Mapping[str, Payload]) -> Iterable[tuple[float, float]]:
    """(start, seconds) of every existing interval not written by us, including entries batched
    inside the app's `multi` container docs. Non-breast feeds (bottle, solids) are ignored."""
    for did, data in docs.items():
        if is_imported(did):
            continue
        entries = data.get("data", {}).values() if data.get("multi") else (data,)
        for e in entries:
            if not isinstance(e, dict) or "start" not in e:
                continue
            if kind == "sleep":
                yield float(e["start"]), float(e.get("duration") or 0)
            elif e.get("mode") == "breast":
                yield float(e["start"]), float(e.get("leftDuration") or 0) + float(e.get("rightDuration") or 0)


def _overlaps(events: Sequence[Event], existing: Snapshot) -> dict[int, Overlap]:
    """For each event index, the first existing entry we did not write that overlaps it.

    Only the same type is compared (sleep with sleep, breastfeeding with breastfeeding):
    a sleep overlapping a feed is normal and not a duplicate."""
    found: dict[int, Overlap] = {}
    for kind in KINDS:
        theirs = sorted(_spans(kind, existing.get(kind, {})))
        if not theirs:
            continue
        starts = [b0 for b0, _ in theirs]
        longest = max(secs for _, secs in theirs)
        for i, event in enumerate(events):
            if _kind(event) != kind:
                continue
            a0, a1 = event.span.start.timestamp(), event.span.end.timestamp()
            for b0, secs in theirs[bisect_left(starts, a0 - longest - 1) :]:
                if b0 >= a1:
                    break
                if b0 + max(secs, 1) > a0:
                    found[i] = Overlap(kind, event.span.start, datetime.fromtimestamp(b0, UTC), secs)
                    break
    return found


def _kind(event: Event) -> Kind:
    return "sleep" if isinstance(event, Sleep) else "feed"


def plan_import(
    events: Sequence[Event],
    existing: Snapshot,
    tz: ZoneInfo,
    now: float | None = None,
    *,
    include_overlaps: bool = False,
) -> Plan:
    """Diff the desired documents against existing ones by id. Pure.

    An event that overlaps an entry already in Huckleberry (one we did not write) is skipped,
    and a copy imported earlier is deleted, so the Huckleberry entry wins. `include_overlaps`
    imports them anyway."""
    now = time.time() if now is None else now
    overlaps = _overlaps(events, existing)
    ops: list[Op] = []
    for i, event in enumerate(events):
        kind, did, payload = to_doc(event, tz, now)
        have = existing.get(kind, {}).get(did)
        action: Action
        if i in overlaps and not include_overlaps:
            action = "skip" if have is None else "delete"
        elif have is None:
            action = "create"
        else:
            action = "unchanged" if _same(have, payload) else "update"
        ops.append(Op(kind, did, action, event.span.start, payload if action in ("create", "update") else None))
    return Plan(tuple(ops), tuple(overlaps[i] for i in sorted(overlaps)))


def plan_undo(existing: Snapshot) -> Plan:
    ops = [
        Op(kind, did, "delete", datetime.fromtimestamp(float(data.get("start", 0)), UTC), None)
        for kind in KINDS
        for did, data in existing.get(kind, {}).items()
        if is_imported(did)
    ]
    return Plan(tuple(sorted(ops, key=lambda o: o.start)))


# ---- I/O --------------------------------------------------------------------------------------


@dataclass(frozen=True, slots=True)
class Child:
    cid: str
    name: str


class Huckleberry:
    """A session bound to one account and one child. Build it with `Huckleberry.connect`."""

    def __init__(self, *, api: HuckleberryAPI, child: Child) -> None:
        self._api = api
        self.child = child

    @classmethod
    @asynccontextmanager
    async def connect(
        cls, *, email: str, password: str, tz: ZoneInfo, child: str | None
    ) -> AsyncGenerator[Huckleberry]:
        async with aiohttp.ClientSession() as session:
            api = HuckleberryAPI(email=email, password=password, timezone=tz.key, websession=session)
            await api.authenticate()
            yield cls(api=api, child=await _resolve_child(api, child))

    async def snapshot(self) -> dict[Kind, dict[str, Payload]]:
        """Every interval document of this child, by kind and id. Errors propagate, so a
        partial read can never lead to a write."""
        client = await self._firestore()
        out: dict[Kind, dict[str, Payload]] = {}
        for kind in KINDS:
            ref = client.collection(kind).document(self.child.cid).collection("intervals")
            out[kind] = {doc.id: doc.to_dict() or {} async for doc in ref.stream()}
        return out

    async def apply(self, plan: Plan) -> int:
        """Run the plan's pending ops in batches of up to 500. Returns the number of docs touched.

        `set()` replaces the whole document and `delete()` is idempotent, so a crash part-way
        leaves some batches applied, and planning and applying again converges."""
        ops = plan.pending
        bad = [op.doc_id for op in ops if not is_imported(op.doc_id)]
        if bad:
            raise AssertionError(f"refusing to touch documents bdb2hb did not create: {bad[:5]}")
        client = await self._firestore()
        for chunk in batched(ops, _BATCH_LIMIT, strict=False):
            batch = client.batch()
            for op in chunk:
                ref = client.collection(op.kind).document(self.child.cid).collection("intervals").document(op.doc_id)
                if op.action == "delete":
                    batch.delete(ref)
                else:
                    batch.set(ref, op.payload)
            await batch.commit()
        return len(ops)

    async def _firestore(self):
        """The single touch point with library internals."""
        return await self._api._get_firestore_client()  # private API; version pinned in pyproject


async def _resolve_child(api: HuckleberryAPI, wanted: str | None) -> Child:
    user = await api.get_user()
    if user is None or not user.childList:
        raise ChildNotFound("this Huckleberry account has no children")
    children: list[Child] = []
    for ref in user.childList:
        doc = await api.get_child(ref.cid)
        name = (doc.childsName if doc else None) or ref.nickname or ref.cid
        children.append(Child(ref.cid, name))
    if wanted is None:
        if len(children) == 1:
            return children[0]
        raise ChildNotFound(f"several children, pass --child with one of: {[c.name for c in children]}")
    matches = [c for c in children if wanted in (c.cid, c.name) or c.name.lower() == wanted.lower()]
    if len(matches) != 1:
        raise ChildNotFound(f"--child {wanted!r} matched {len(matches)}; children are: {[c.name for c in children]}")
    return matches[0]
